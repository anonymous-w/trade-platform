-- Source archive: incomplete workbook data must not create fictitious customers/invoices/exports.
CREATE TABLE t_packing_import_batch (
  batch_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  file_name VARCHAR(255) NOT NULL,
  file_sha256 CHAR(64) NOT NULL UNIQUE,
  content_sha256 CHAR(64) NOT NULL UNIQUE,
  sheet_name VARCHAR(255) NOT NULL,
  parser_version VARCHAR(30) NOT NULL,
  row_count INTEGER NOT NULL CHECK (row_count BETWEEN 1 AND 10000),
  contract_count INTEGER NOT NULL CHECK (contract_count >= 0),
  review_rows INTEGER NOT NULL CHECK (review_rows BETWEEN 0 AND row_count),
  created_by VARCHAR(50) NOT NULL REFERENCES m_user(user_id),
  created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE t_packing_source_row (
  source_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  batch_id BIGINT NOT NULL REFERENCES t_packing_import_batch(batch_id) ON DELETE CASCADE,
  source_row INTEGER NOT NULL CHECK (source_row >= 5),
  contract_no TEXT NOT NULL,
  equipment_name TEXT NOT NULL,
  model_no TEXT NOT NULL,
  part_name TEXT NOT NULL,
  needs_review BOOLEAN NOT NULL,
  -- JSON retains typed numbers, missing values, raw B:P cells, formula text and merged ranges.
  -- No premature business identifiers, rounding, unit conversion or fabricated master records.
  data JSONB NOT NULL CHECK (jsonb_typeof(data) = 'object'),
  UNIQUE(batch_id,source_row)
);
CREATE INDEX ix_packing_source_contract ON t_packing_source_row(contract_no);
CREATE INDEX ix_packing_source_review ON t_packing_source_row(batch_id,needs_review,source_row);
COMMENT ON TABLE t_packing_source_row IS 'Excel source archive; unverified source data, excluded from confirmed export/container totals';

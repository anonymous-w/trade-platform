-- M_USER: 系统登录用户及基础角色 / 核心
CREATE TABLE M_USER (
    USER_ID VARCHAR(50) NOT NULL,
    USER_NAME VARCHAR(100) NOT NULL,
    PASSWORD_HASH VARCHAR(255) NOT NULL,
    ROLE_CODE VARCHAR(20) NOT NULL DEFAULT 'USER',
    EMAIL VARCHAR(254),
    ENABLED_FLG BOOLEAN NOT NULL DEFAULT TRUE,
    FAILED_COUNT INTEGER NOT NULL DEFAULT 0,
    LOCKED_UNTIL TIMESTAMPTZ,
    LAST_LOGIN_AT TIMESTAMPTZ,
    CREATED_BY VARCHAR(50),
    CREATED_AT TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UPDATED_BY VARCHAR(50),
    UPDATED_AT TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT PK_M_USER PRIMARY KEY (USER_ID),
    CONSTRAINT FK_M_USER_01 FOREIGN KEY (CREATED_BY) REFERENCES M_USER (USER_ID),
    CONSTRAINT FK_M_USER_02 FOREIGN KEY (UPDATED_BY) REFERENCES M_USER (USER_ID),
    CONSTRAINT CK_M_USER_01 CHECK (ROLE_CODE IN ('ADMIN','USER')),
    CONSTRAINT CK_M_USER_02 CHECK (FAILED_COUNT BETWEEN 0 AND 999)
);

CREATE INDEX IX_M_USER_FK01 ON M_USER (CREATED_BY);
CREATE INDEX IX_M_USER_FK02 ON M_USER (UPDATED_BY);

